def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="build the document, compare with the file on disk, write nothing")
    ap.add_argument("--out", default=os.path.join(REPO, "results", "language", "results.md"))
    a = ap.parse_args()

    text = build()
    if a.check:
        old = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else ""
        print("[CHECK] %s: %s" % (a.out, "MATCHES" if old == text else "DIFFERS"))
        return 0 if old == text else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d lines)" % (a.out, text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
