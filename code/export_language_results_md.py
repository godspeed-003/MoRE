#!/usr/bin/env python
"""export_language_results_md.py -- GENERATE results/language/results.md.

The paper-facing empirical record for the language task. It is GENERATED, not
written by hand, for the reason CLAUDE.md 5 gives: numbers that are transcribed
by hand are numbers that drift from the artifacts they came from. Every figure
in the output is read from a stored file at generation time, and anything that
is not present is emitted as N/A rather than filled in from memory.

Inputs (all tracked, all produced by the tools in code/):
    results/language/results.json        the canonical export (admissions, pairwise,
                                         aggregate metrics, provenance)
    results/language/eval_summary.md     the compute-bracketed score table
    results/flops_language.json          inference FLOPs per arm
    results/language/dynamic_rerun.json  the update-state cosine probe
    results/language/subspace.json       the subspace-trapping probe
    results/language/{blimp,ewok}.json   the two benchmark probes
    results/language/ood_pile_*.json     the out-of-domain probes
    data/lang/wikitext-103/dataset_meta.json   the corpus manifest
    runs/<run>/results.tsv               per-epoch training dynamics
    code/canonical_spec_language.json    the frozen specification

Usage:
    python code/export_language_results_md.py
    python code/export_language_results_md.py --check   # verify, write nothing
"""

