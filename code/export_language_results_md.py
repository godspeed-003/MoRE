def load(rel, required=True):
    p = os.path.join(REPO, rel)
    if not os.path.exists(p):
        if required:
            raise SystemExit("[FAIL] required artifact missing: %s" % rel)
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def mean_of(agg, key):
    v = agg["metrics"].get(key)
    if isinstance(v, dict):
        m, s = v.get("mean"), v.get("std")
        if m is None:
            return None, None
        return m, s
    return (v, None) if v is not None else (None, None)


def fmt(x, nd=4):
    if x is None:
        return "N/A"
    try:
        if x != x:            # NaN: a quantity that does not exist, not zero
            return "N/A"
    except TypeError:
        return str(x)
    return "%.*f" % (nd, x)


def pstd(x, nd=4):
    return "N/A" if x is None else ("%.*f" % (nd, x))


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


_NUM = __import__("re").compile(r"-?\d+(?:\.\d+)?")


def frozen_value(note):
    """The frozen scalar inside a `frozen_by` note, which is written as prose.

    The spec stores each field's value as a sentence that opens with the value
    ("FROZEN AT 3 BY T-L7.1, ...", "DEFINITIONAL-BY-PROTOCOL. 256, ...") followed
    by the reasoning. This pulls the first number, which is the frozen value in
    every case the spec actually uses, and returns N/A if there is not one.
    """
    if not isinstance(note, str):
        return "N/A"
    m = _NUM.search(note)
    return m.group(0) if m else "N/A"


def first_sentence(note, limit=190):
    """The opening sentence of a note, trimmed -- the 'why' column."""
    if not isinstance(note, str):
        return "N/A"
    s = note.replace("\n", " ")
    for stop in (". ", "; "):
        i = s.find(stop)
        if i != -1:
            s = s[:i + 1]
            break
    s = s.strip()
    return s if len(s) <= limit else s[:limit - 3].rsplit(" ", 1)[0] + "..."


