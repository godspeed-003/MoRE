    A("   own Limitations rather than leaving it to a reader to notice.")
    A("4. **That ACT's learned policy is what makes recursion work.** Untested: the")
    A("   depth-matched-TRAINED control was never run (section 9).")
    A("5. **That the out-of-domain ordering is a robustness result.** It is exploratory,")
