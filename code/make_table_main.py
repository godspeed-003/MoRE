# -*- coding: utf-8 -*-
r"""make_table_main.py -- generate the paper's Table 1 (tab:main) from results files.

    python code/make_table_main.py            # rewrite the table in place
    python code/make_table_main.py --check    # exit 1 if the source is stale

WHY THIS EXISTS (T-LA.22). Table 1 was assembled by hand at T-LA.15, when two
tables were merged into one, and its standard deviations were restored by hand
after the merge dropped them. The paper's Reproducibility Statement nevertheless
says every table is generated and no number was copied by hand -- which was false
for exactly the table that carries the headline. CLAUDE.md 5 forbids hand-copied
results tables for the same reason: the next change of an input silently leaves
the table behind. T-LA.22 changed three inputs at once (FLOPs re-costed at the
admitted 5-seed depth, the document-capped OOD set, same-card throughput), which
is what forced the issue.

HOW. The table lives in paper/common/04_results.tex between the two marker lines

    % >>>GENERATED:tab_main ...
    % <<<GENERATED:tab_main

and this script replaces everything between them. Edit THIS FILE to change the
table's wording or layout; an edit made between the markers is overwritten.

SOURCES -- one per row, all generated by other scripts, none typed in:
  val loss, params, floor, pairwise   results/language/results.json  (export_results)
  test loss                           results/language/stratified_test.json
  OOD loss, same-card throughput      results/language/ood_pile_capped.json  (eval_ood)
  BLiMP                               results/language/blimp.json
  FLOPs/token, FLOPs multiplier       results/flops_language.json  (flops_accounting)
"""

from __future__ import annotations

import json
import math
import os
import sys
from pathlib import Path

REPO = Path(os.path.dirname(os.path.abspath(__file__))).parent
RES = REPO / "results" / "language"
TARGET = REPO / "paper" / "common" / "04_results.tex"
BEGIN = "% >>>GENERATED:tab_main"
END = "% <<<GENERATED:tab_main"
ARMS = ("moe", "mor", "more")


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def gather():
    res = _load(RES / "results.json")
    agg = res["aggregate"]

    def canon(arm, key):
        m = agg[arm]["metrics"][key]
        return m["mean"], m["std"]

    def by_arm(fname, mean_key, std_key):
        d = _load(RES / fname)["by_arm"]
        return {a: (d[a][mean_key], d[a][std_key]) for a in ARMS}

    ood = _load(RES / "ood_pile_capped.json")
    fl = {a["arm"]: a for a in _load(REPO / "results" / "flops_language.json")["arms"]}
    fpt = {a: fl[a]["flops_per_token_at_mean_depth"] for a in ARMS}
    return {
        "val": {a: canon(a, "val/task_loss") for a in ARMS},
        "test": by_arm("stratified_test.json", "mean_loss", "std_loss"),
        "ood": {a: (ood["by_arm"][a]["mean_loss"], ood["by_arm"][a]["std_loss"])
                for a in ARMS},
        "blimp": {a: (100 * m, 100 * s) for a, (m, s) in
                  by_arm("blimp.json", "overall_mean", "overall_std").items()},
        "params": {a: int(agg[a]["metrics"]["total_params"]["mean"]) for a in ARMS},
        "floor": float(res["primary_metric_floor"]),
        "pairwise": res["pairwise"],
        "fpt": fpt,
        "x": {a: fpt[a] / fpt["moe"] for a in ARMS},
        "thr": {a: ood["by_arm"][a]["blocks_per_sec_mean"] for a in ARMS},
        "device": ood["cells"][0].get("device", "one GPU"),
        "ood_docs": (ood.get("composition") or {}).get("n_documents"),
        "ood_cap": (ood.get("composition") or {}).get("cap_tokens_per_doc"),
        "ood_blocks": ood["n_blocks"],
    }


def bold(s, on):
    return r"\textbf{%s}" % s if on else s


def score_row(label, data, x, higher_better, fmt, unit_fmt):
    """One upper-block row: MoE plain, MoR/MoRE with (diff, FLOPs-x, |diff|/x)."""
    ref = data["moe"][0]
    best_arm = (max if higher_better else min)(ARMS, key=lambda a: data[a][0])
    per_x = {a: abs(data[a][0] - ref) / x[a] for a in ("mor", "more")}
    best_px = max(per_x, key=per_x.get)
    cells = []
    for a in ARMS:
        m, s = data[a]
        core = bold(fmt(m), a == best_arm) + r"\,$\pm$\," + fmt(s)
        if a == "moe":
            cells.append(core)
            continue
        cells.append(core + " ($%s$, %.2f$\\times$, %s)" % (
            unit_fmt(m - ref), x[a], bold("%.3f" % per_x[a], a == best_px)))
    return label + " & " + " & ".join(cells) + r" \\"


def render(g) -> str:
    x = g["x"]
    f3 = lambda v: "%.3f" % v
    f2 = lambda v: "%.2f" % v
    sgn3 = lambda v: ("%+.3f" % v).replace("-", "-")
    sgn2 = lambda v: "%+.2f" % v

    pw = {p["pair"]: p for p in g["pairwise"]}
    def stat(pair, show):
        p = pw[pair]
        return r"%s $%+.4f$ ($d\,{%+.1f}$)" % (show, p["gap"], p["cohens_d"])
    all_floor = all(p.get("at_floor") for p in g["pairwise"])

    lines = [
        BEGIN + " (code/make_table_main.py -- do not edit by hand; regenerate)",
        r"\begin{table*}[t]",
        r"\centering",
        r"\footnotesize",
        r"\caption{All results, five seeds, mean$\,\pm\,$std. \textbf{Upper block:} each"
        r" cell is \emph{score (difference vs MoE, inference FLOPs$\times$ vs MoE,"
        r" $|$difference$|$ per FLOPs-multiplier)}; MoE is the reference arm, so its cells"
        r" carry the score alone. Scores are lower-better for loss and higher-better for"
        r" accuracy; the third number is a \textbf{modulus}, so it is higher-better on"
        r" \emph{every} row---how much quality each unit of compute bought. Quality at"
        r" matched parameters and quality per unit of compute are distinct axes and we"
        r" never substitute one for the other. Validation loss is the primary metric"
        r" (final epoch; \emph{best} equals \emph{last} on all 15 cells, so no model"
        r" selection occurred). Pairwise, exact two-sided randomization test"
        + (r", every comparison at the floor $p_{\min}=0.00794$: " if all_floor else ": ")
        + "; ".join([stat("MoRE - MoE", r"MoRE$-$MoE"),
                     stat("MoRE - MoR", r"MoRE$-$MoR"),
                     stat("MoE - MoR", r"MoE$-$MoR")])
        + r". OOD is held-out Pile text: %d blocks from %d documents, each contributing"
          r" at most %d tokens (\S\ref{sec:ood})." % (g["ood_blocks"], g["ood_docs"],
                                                       g["ood_cap"])
        + r" \textbf{Lower block:} $\Delta$ floor is the margin below the bigram baseline"
          r" of %.4f nats (positive \emph{beats} it); FLOPs are inference FLOPs per token"
          r" at each arm's measured mean depth (Appendix~\ref{app:flops}); throughput is"
          r" inference for all fifteen checkpoints on one GPU, identical blocks and batch."
          r" The OOD, BLiMP and throughput rows are \textbf{exploratory}---outside both"
          r" declared families, uncorrected.}" % g["floor"],
        r"\label{tab:main}",
        r"\vspace{2pt}",
        r"\begin{tabular}{llll}",
        r"\toprule",
        r"Eval & MoE & MoR & MoRE \\",
        r"\midrule",
        score_row("Val loss (nats)", g["val"], x, False, f3, sgn3),
        score_row("Test loss (nats)", g["test"], x, False, f3, sgn3),
        score_row("OOD loss (nats)", g["ood"], x, False, f3, sgn3),
        score_row("BLiMP (acc)", g["blimp"], x, True, f2, sgn2),
        r"\midrule",
    ]
    ppl = {a: math.exp(g["val"][a][0]) for a in ARMS}
    lines.append("Parameters & " + " & ".join(
        "{:,}".format(g["params"][a]).replace(",", "{,}") for a in ARMS) + r" \\")
    lines.append("Val perplexity & " + " & ".join(
        bold("%.1f" % ppl[a], a == min(ppl, key=ppl.get)) for a in ARMS) + r" \\")
    lines.append(r"$\Delta$ vs bigram floor & " + " & ".join(
        "$%+.4f$" % (g["floor"] - g["val"][a][0]) for a in ARMS) + r" \\")
    lines.append("Inference FLOPs/token & " + " & ".join(
        bold(r"%.2f\,M" % (g["fpt"][a] / 1e6) if g["fpt"][a] < 1e7
             else r"%.1f\,M" % (g["fpt"][a] / 1e6),
             a == min(g["fpt"], key=g["fpt"].get)) for a in ARMS) + r" \\")
    lines.append("Throughput (blocks/s) & " + " & ".join(
        bold("%.0f" % g["thr"][a], a == max(g["thr"], key=g["thr"].get))
        for a in ARMS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", END]
    return "\n".join(lines) + "\n"


def render_family_depth() -> str:
    """tab:family-depth -- mean recursion depth by POS family, MoR vs MoRE.

    Source: depth/mean_by_family/* in each ADMITTED run (results.json), averaged
    over the five seeds per arm. Validation pass; positions with a mapped family,
    each block's last position excluded (depth_key_provenance in metrics.json).
    MoE is omitted: its depth is 1 by construction, so a row would be a constant.
    """
    res = _load(RES / "results.json")
    fams = [("L1_FUNCTION", "Function"), ("L2_NOUN", "Noun"), ("L3_VERB", "Verb"),
            ("L4_MODIFIER", "Modifier"), ("L5_PUNCT_SYM", "Punct."),
            ("L6_NUM_SUBWORD", "Num./subw.")]
    means = {}
    for arm in ("mor", "more"):
        rows = [r["metrics"] for r in res["admitted_runs"] if r["architecture"] == arm]
        means[arm] = [sum(m["depth/mean_by_family/" + k] for m in rows) / len(rows)
                      for k, _ in fams]
    spread = {a: max(v) - min(v) for a, v in means.items()}
    lines = [
        "% >>>GENERATED:tab_family_depth (code/make_table_main.py -- do not edit by hand; regenerate)",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\caption{Mean recursion depth (of $T=7$) by the part-of-speech family of the"
        r" token, validation split, mean over five seeds. MoR's depth varies across"
        r" families by %.3f steps; MoRE's by %.3f, $%.0f\times$ less. Unlike a"
        r" depth--difficulty correlation on an arm whose depth is nearly constant, this"
        r" measures the absence of allocation directly. Exploratory, uncorrected.}"
        % (spread["mor"], spread["more"], spread["mor"] / spread["more"]),
        r"\label{tab:family-depth}",
        r"\vspace{2pt}",
        r"\begin{tabular}{l" + "c" * len(fams) + "c}",
        r"\toprule",
        "Arm & " + " & ".join(n for _, n in fams) + r" & spread \\",
        r"\midrule",
    ]
    for arm, label in (("mor", "MoR"), ("more", "MoRE")):
        lines.append(label + " & " + " & ".join("%.3f" % v for v in means[arm])
                     + r" & \textbf{%.3f} \\" % spread[arm])
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}",
              "% <<<GENERATED:tab_family_depth"]
    return "\n".join(lines) + "\n"


def _splice(src: str, begin: str, end: str, body: str) -> str:
    if begin not in src or end not in src:
        raise SystemExit(f"[FAIL] markers {begin!r} missing from {TARGET}")
    i = src.index(begin)
    j = src.index(end) + len(end)
    if j < len(src) and src[j] == "\n":
        j += 1
    return src[:i] + body + src[j:]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    src = TARGET.read_text(encoding="utf-8")
    new = _splice(src, BEGIN, END, render(gather()))
    new = _splice(new, "% >>>GENERATED:tab_family_depth",
                  "% <<<GENERATED:tab_family_depth", render_family_depth())
    if "--check" in argv:
        stale = new != src
        print("generated tables are STALE -- run code/make_table_main.py" if stale
              else "generated tables are current")
        return 1 if stale else 0
    TARGET.write_text(new, encoding="utf-8", newline="\n")
    print(f"-> {TARGET.relative_to(REPO)} (tab:main, tab:family-depth regenerated)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
