# -*- coding: utf-8 -*-
"""eval_summary_table.py -- the compute-adjusted evaluation summary for the paper.

    python code/eval_summary_table.py

Reads the exploratory eval JSONs under results/language/ and the authoritative FLOPs
record (results/flops_language.json), and writes results/language/eval_summary.md: one
table of every eval x every arm, each score annotated with (rank, compute multiple).

THE COMPUTE BRACKET. For each eval the WORST-scoring arm is the reference; every arm's
score carries `(rank, N.Nx)` where N.Nx is that arm's inference FLOPs per token divided
by the reference arm's. So a better score at a higher multiple reads directly as "this
much more compute bought this much more quality". FLOPs, not wall-clock, is the compute
measure: wall-clock is latency-bound and implementation-dependent (CLAUDE.md 4 forbids
calling a FLOP ratio a speedup); the measured throughput is reported in its own row for
honesty, where MoRE's per-token dispatch makes it slower than its FLOP count implies.

EVERYTHING HERE IS EXPLORATORY. Scored with the trained wikitext-103 tokenizer, so BLiMP/
EWoK absolute values are not comparable to published models; only cross-arm is. The exact
randomization test's 5v5 floor is 0.00794 and the headline comparisons sit on it. This
file is a derived SUMMARY and is NOT the canonical results_tables.md (that is export_results).
"""

from __future__ import annotations

import json
import math
import os
from pathlib import Path

REPO = Path(os.path.dirname(os.path.abspath(__file__))).parent
RES = REPO / "language" if (REPO / "language").is_dir() else REPO / "results" / "language"
ARMS = ["moe", "mor", "more"]
LABEL = {"moe": "MoE", "mor": "MoR", "more": "MoRE"}


def load(name):
    p = RES / name
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def flops_per_token():
    """Inference FLOPs/token at each arm's measured mean depth, and the ratio vs the
    cheapest arm. Authoritative source: results/flops_language.json."""
    d = json.loads((REPO / "results" / "flops_language.json").read_text(encoding="utf-8"))
    fpt, tp = {}, {}
    for a in d["arms"]:
        fpt[a["arm"]] = a["flops_per_token_at_mean_depth"]
        tp[a["arm"]] = a.get("throughput_items_sec")
    base = min(fpt.values())
    ratio = {k: v / base for k, v in fpt.items()}
    return fpt, ratio, tp


def arm_scores(j, higher_better):
    """{arm: (mean, std)} from a by_arm block, picking the right score key."""
    out = {}
    for a, v in (j.get("by_arm", {}) if j else {}).items():
        m = v.get("overall_mean", v.get("mean_loss"))
        s = v.get("overall_std")
        if s is None:
            s = v.get("std_loss")
        if m is not None:
            out[a] = (m, s)
    return out


def rank_tag(scores, higher_better):
    """arm -> 'best'/'mid'/'worst' by score (ties share a label)."""
    vals = sorted(scores.items(), key=lambda kv: kv[1][0], reverse=higher_better)
    tags = {}
    names = ["best", "mid", "worst"]
    for i, (a, _) in enumerate(vals):
        tags[a] = names[i] if i < 3 else "worst"
    return tags, vals[-1][0]        # tags, worst-scoring arm


def fmt_pct(m, s):
    return f"{m*100:.2f}%" + (f" +- {s*100:.2f}" if s else "")


def fmt_nats(m, s):
    return f"{m:.4f}" + (f" +- {s:.4f}" if s else "")


def main():
    fpt, ratio, tp = flops_per_token()

    EVALS = [
        ("Val loss (nats, lower better)", "stratified_val.json", False, fmt_nats),
        ("Test loss (nats, lower better)", "stratified_test.json", False, fmt_nats),
        ("OOD perplexity loss (nats, lower)", "ood_pile_test.json", False, fmt_nats),
        ("BLiMP (acc, higher better)", "blimp.json", True, fmt_pct),
        ("EWoK (acc, chance 50%)", "ewok.json", True, fmt_pct),
    ]

    lines = []
    lines.append("# Compute-adjusted evaluation summary (language)\n")
    lines.append("GENERATED by `code/eval_summary_table.py` from the eval JSONs and "
                 "`results/flops_language.json`. Do not edit by hand; regenerate.\n")
    lines.append("- EXPLORATORY. Scored with the wikitext-103 8192-BPE tokenizer, so "
                 "BLiMP/EWoK absolute values are not comparable to published models; only "
                 "the cross-arm comparison is. Uncorrected; the exact-test 5v5 floor is "
                 "0.00794 and the headline gaps sit on it.\n")
    lines.append("- **Compute bracket** = inference FLOPs/token vs the cheapest arm, from "
                 "`flops_language.json` (at each arm's measured mean depth). It annotates "
                 "every score as `(rank, Nx)`: a better score at a higher multiple is that "
                 "much more compute bought for that much more quality.\n")

    # Compute reference block.
    lines.append("\n## Compute per arm (the bracket's basis)\n")
    lines.append("| arm | FLOPs/token | FLOPs x vs cheapest | throughput items/s | wall-clock x slower |\n|---|---|---|---|---|")
    base_tp = max(v for v in tp.values() if v)
    for a in ARMS:
        wc = base_tp / tp[a] if tp.get(a) else None
        lines.append(f"| {LABEL[a]} | {fpt[a]:,.0f} | {ratio[a]:.2f}x | "
                     f"{tp[a]:.1f} | {wc:.2f}x |" if tp.get(a) else
                     f"| {LABEL[a]} | {fpt[a]:,.0f} | {ratio[a]:.2f}x | NA | NA |")
    lines.append("\nFLOPs and wall-clock disagree on purpose: MoR does the most FLOPs "
                 "(deep single block) yet MoRE is often the slowest in wall-clock, because "
                 "MoRE's per-token expert dispatch is latency-bound. FLOPs is the compute "
                 "measure; throughput is reported so the latency cost is visible.\n")

    # Per-eval table.
    lines.append("\n## Scores with compute bracket\n")
    header = "| eval | " + " | ".join(LABEL[a] for a in ARMS) + " |"
    lines.append(header + "\n|" + "---|" * (len(ARMS) + 1))
    for title, fname, higher, fmt in EVALS:
        j = load(fname)
        sc = arm_scores(j, higher)
        if not sc:
            lines.append(f"| {title} | " + " | ".join("NA" for _ in ARMS) + " |")
            continue
        tags, worst_arm = rank_tag(sc, higher)
        worst_ratio = ratio.get(worst_arm, 1.0)
        cells = []
        for a in ARMS:
            if a not in sc:
                cells.append("NA")
                continue
            m, s = sc[a]
            mult = ratio[a] / worst_ratio
            cells.append(f"{fmt(m, s)} ({tags[a]}, {mult:.2f}x)")
        lines.append(f"| {title} | " + " | ".join(cells) + " |")

    # Efficiency note: quality gain per extra compute, val loss.
    sv = arm_scores(load("stratified_val.json"), False)
    if {"moe", "mor", "more"} <= set(sv):
        def nats_per_x(a):
            gain = sv["moe"][0] - sv[a][0]          # nats improved vs MoE
            extra = ratio[a] - ratio["moe"]         # extra FLOPs multiples vs MoE
            return gain / extra if extra else float("nan")
        lines.append("\n## Compute efficiency (val loss gain over MoE per extra FLOPs-x)\n")
        lines.append("| arm | nats improved vs MoE | extra FLOPs x | nats per extra x |\n|---|---|---|---|")
        for a in ("more", "mor"):
            lines.append(f"| {LABEL[a]} | {sv['moe'][0]-sv[a][0]:+.4f} | "
                         f"+{ratio[a]-ratio['moe']:.2f}x | {nats_per_x(a):.4f} |")
        lines.append("\nMoRE converts extra compute into quality far more efficiently than "
                     "MoR (higher nats-per-x): most of MoR's gain for a fraction of the "
                     "FLOPs. MoR reaches the lowest absolute loss but pays ~9x the compute.\n")

    out = RES / "eval_summary.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"-> {out}")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
