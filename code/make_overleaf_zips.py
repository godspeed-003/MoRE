"""make_overleaf_zips.py -- upload bundles, without the build artifacts.

`shutil.make_archive` takes whatever is on disk, so once the papers were compiled
locally the bundles jumped from ~315 KB to ~912 KB by carrying main.pdf and the
aux/log/bbl files. Those are regenerated by Overleaf on the first build and only
invite confusion about which PDF is current, so they are excluded here.

Kept: main.tex, sections/, refs.bib, fig/, the venue style files, and
VERIFY_BEFORE_SUBMIT.md.
"""
import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.join(os.path.dirname(HERE), "paper")

DROP_EXT = {".pdf", ".aux", ".log", ".out", ".bbl", ".blg",
            ".lof", ".lot", ".toc", ".fls", ".fdb_latexmk", ".synctex.gz"}
KEEP_PDF_IN = {"fig"}          # figures ARE pdf and must stay


def bundle(venue, out_name):
    src = os.path.join(PAPER, venue)
    out = os.path.join(PAPER, out_name + ".zip")
    if os.path.exists(out):
        os.remove(out)
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _dirs, files in os.walk(src):
            rel_root = os.path.relpath(root, PAPER)
            parts = set(rel_root.replace("\\", "/").split("/"))
            for f in sorted(files):
                ext = os.path.splitext(f)[1].lower()
                if ext in DROP_EXT and not (parts & KEEP_PDF_IN):
                    continue
                full = os.path.join(root, f)
                z.write(full, os.path.join(rel_root, f))
                n += 1
    return out, n, os.path.getsize(out)


if __name__ == "__main__":
    print("building Overleaf upload bundles (build artifacts excluded)\n")
    for venue, name in (("tmlr_submission", "overleaf_tmlr"),
                        ("acl_submission", "overleaf_acl")):
        path, n, size = bundle(venue, name)
        print(f"  {os.path.basename(path):22} {n:>3} files  {size / 1024:>6.0f} KB")
    print("\n  Upload the zip to a new Overleaf project and set the compiler to")
    print("  pdfLaTeX. Read VERIFY_BEFORE_SUBMIT.md inside before submitting.")
